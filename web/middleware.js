const regionEndpoint = countryCode => {
  if (amer.includes(countryCode)) {
    return '/us-api/'
  }

  if (emea.includes(countryCode)) {
    return '/eu-api/'
  }

  return '/api/'
}

export function middleware(request) {
  const country = request.geo?.country || ''
  if (country != '') {
    const url = request.url.replace('/api/', regionEndpoint(country))
    return NextResponse.rewrite(url)
  }

  // return NextResponse.rewrite(new URL('/api/us', request.url))
}

